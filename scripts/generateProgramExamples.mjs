// Writes src/programExamples.mjs: the worked examples the code editor's Template ▾ offers (docs/proposals/codeEditor.md, "Starting a
// program"), with their sources from examples/providers, so the desktop window and the web edition's panel have them without reading
// files. tests/programExamples.test.mjs fails when the file is not what this writes, and tests/engine/programTemplates.mjs runs every
// example through Check program. Run: node scripts/generateProgramExamples.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDirectory = join(dirname(fileURLToPath(import.meta.url)), '..');
const examplesDirectory = join(rootDirectory, 'examples', 'providers');
const outputPath = join(rootDirectory, 'src', 'programExamples.mjs');

// Each example: what Template ▾ calls it, which kind of program it is (it is offered for a program of that kind), a line saying what it
// does, and its sources by language.
export const programExampleList = [
    { id: 'pidController', label: 'PID controller', kind: 'node', description: 'A digital PID controller sampled every 10 ms, with memory, a clock and anti-windup.',
        files: { cpp: 'pidController.cpp', python: 'pidController.py' } },
    { id: 'conduction', label: 'Conduction', kind: 'relationship', description: 'Heat conducted from a hot body to a cold one.',
        files: { cpp: 'conduction.cpp', python: 'conduction.py' } },
    { id: 'lookupTable', label: 'Lookup table', kind: 'relationship', description: 'A value from a table of points, interpolated, refusing one outside the table.',
        files: { cpp: 'lookupTable.cpp', python: 'lookupTable.py' } },
    { id: 'csvReplay', label: 'CSV replay', kind: 'relationship', description: 'A recorded signal read from a CSV file when the run starts, replayed in time.',
        files: { cpp: 'csvReplay.cpp', python: 'csvReplay.py' } }
];

export async function generatedProgramExamplesModule() {
    const examples = [];
    for (const { files, ...example } of programExampleList) {
        const sources = {};
        for (const [language, file] of Object.entries(files)) sources[language] = await readFile(join(examplesDirectory, file), 'utf8');
        examples.push({ ...example, sources });
    }
    return '/* Copyright © 2026 Zenin Easa Panthakkalakath */\n\n'
        + '// Generated by scripts/generateProgramExamples.mjs from examples/providers; do not edit. tests/programExamples.test.mjs fails when\n'
        + '// it is out of date.\n\n'
        + `export const programExamples = ${JSON.stringify(examples, null, 4)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    await writeFile(outputPath, await generatedProgramExamplesModule());
    console.log(`Wrote ${outputPath}.`);
}
