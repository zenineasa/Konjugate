// How the ownership block (src/ownership.mjs, docs/proposals/modelOwnership.md) behaves where it meets the rest of the application:
// generated code and FMU descriptions, the encrypted file header, the command line's save, and the assistant.

import assert from 'node:assert/strict';
import { scryptSync } from 'node:crypto';
import test from 'node:test';
import { summarizeDocumentForAssistant } from '../src/assistantOperations.mjs';
import { decodeProjectFile, encodeProjectFile, inspectProjectFile } from '../src/projectFile.mjs';
import { decodeProjectContent, encodeProjectContent, inspectProjectContent } from '../src/browserProjectCodec.mjs';
import { generateStandaloneProgram } from '../src/codeExport.mjs';
import { modelDescriptionXml } from '../src/fmiExport.mjs';
import { publicNoticeOf, stampProjectContent } from '../src/ownership.mjs';

const ownership = { owner: 'Acme Thermal Ltd', copyright: 'Copyright © 2026 Acme Thermal Ltd', license: { id: 'MIT' }, contact: 'models@acme.example' };

function document(withOwnership) {
    return {
        format: 'konjugate', version: 1, metadata: { projectName: 'Test project' },
        runConfigurations: [{ id: 900, globalTimeStep: 0.1, outputInterval: 0.1 }], activeRunConfigurationId: 900, exportDefaultTargetTime: 5,
        nodes: [], edges: [], ...(withOwnership ? { ownership } : {})
    };
}

test('generated programs open with the owner, copyright and license when the project names them', () => {
    const cpp = generateStandaloneProgram(document(true), 'cpp');
    assert.match(cpp, /^\/\/ Generated by Konjugate[^\n]*\n\/\/ Copyright © 2026 Acme Thermal Ltd\n\/\/ License: MIT\n\/\/ Contact: models@acme\.example\n/);
    const python = generateStandaloneProgram(document(true), 'python');
    assert.match(python, /# Copyright © 2026 Acme Thermal Ltd\n# License: MIT\n# Contact: models@acme\.example\n/);
});

test('generated programs say nothing about ownership when the project names no one', () => {
    const cpp = generateStandaloneProgram(document(false), 'cpp');
    assert.doesNotMatch(cpp, /License:|Copyright|Owner:/);
});

test('a line break in a notice cannot end the comment it is written in', () => {
    const source = generateStandaloneProgram({ ...document(false), ownership: { copyright: 'first\nint injected = 1;' } }, 'cpp');
    assert.doesNotMatch(source, /^int injected/m);
});

test('an FMU description carries author, copyright and license, escaped, and none when there are none', () => {
    const xml = modelDescriptionXml({ modelName: 'm', guid: 'g', modelIdentifier: 'm', stateVariables: [], parameterVariables: [], supportsStateCapture: false, ownership: { ...ownership, owner: 'A & "B" <C>' } });
    assert.match(xml, /guid="g" author="A &amp; &quot;B&quot; &lt;C&gt;" copyright="Copyright © 2026 Acme Thermal Ltd" license="MIT" generationTool="Konjugate"/);
    const bare = modelDescriptionXml({ modelName: 'm', guid: 'g', modelIdentifier: 'm', stateVariables: [], parameterVariables: [], supportsStateCapture: false });
    assert.match(bare, /guid="g" generationTool="Konjugate"/);
});

const content = JSON.stringify({ format: 'konjugate', version: 1, nodes: [], edges: [], ownership: { owner: 'Acme', publicNotice: 'Ask models@acme.example for the password' } });

test('an encrypted file shows the owner\'s notice before it is unlocked, and the model stays encrypted', async () => {
    const notice = publicNoticeOf(content);
    assert.equal(notice, 'Ask models@acme.example for the password');
    const encoded = await encodeProjectFile(content, { password: 'pw', scryptCost: 2 ** 14, publicNotice: notice });
    assert.deepEqual(inspectProjectFile(encoded), { format: 'kjt', encrypted: true, version: 1, publicNotice: notice });
    assert.equal(encoded.includes(Buffer.from('Acme"')), false, 'the owner name is only inside the encrypted payload');
    assert.equal(await decodeProjectFile(encoded, { password: 'pw' }), content);
});

test('an unencrypted file has no header notice, and a notice is never longer than the limit', async () => {
    const plain = await encodeProjectFile(content, { publicNotice: 'visible anyway' });
    assert.deepEqual(inspectProjectFile(plain), { format: 'kjt', encrypted: false, version: 1 });
    const long = await encodeProjectFile(content, { password: 'pw', scryptCost: 2 ** 14, publicNotice: 'x'.repeat(1000) });
    assert.equal(inspectProjectFile(long).publicNotice.length, 300);
});

test('the browser codec writes and reads the same header notice', async () => {
    // The browser derives its key with a bundled scrypt (window.scrypt); Node's own gives the same key for the same cost parameters.
    globalThis.window = { scrypt: { scrypt: async (password, salt, cost, blockSize, parallelization, length) => new Uint8Array(scryptSync(password, salt, length, { N: cost, r: blockSize, p: parallelization, maxmem: 256 * 1024 * 1024 })) } };
    try {
    const encoded = await encodeProjectContent(content, { password: 'pw', scryptCost: 2 ** 14, publicNotice: 'Ask for the password' });
    assert.deepEqual(inspectProjectContent(encoded), { format: 'kjt', encrypted: true, version: 1, publicNotice: 'Ask for the password' });
    assert.equal((await decodeProjectContent(encoded, { password: 'pw' })).content, content);
    const plain = await encodeProjectContent(content, { publicNotice: 'x' });
    assert.deepEqual(inspectProjectContent(plain), { format: 'kjt', encrypted: false, version: 1 });
    } finally {
        delete globalThis.window;
    }
});

test('a file written by the desktop codec reads its notice in the browser codec', async () => {
    const desktop = await encodeProjectFile(content, { password: 'pw', scryptCost: 2 ** 14, publicNotice: 'Hello' });
    assert.equal(inspectProjectContent(new Uint8Array(desktop)).publicNotice, 'Hello');
});

test('the command line\'s save updates only the save times and version of the block', () => {
    const original = JSON.stringify({ format: 'konjugate', version: 1, copyright: 'Copyright © 2026 Zenin Easa Panthakkalakath', nodes: [{ id: 1 }], edges: [], addonData: { a: 1 }, ownership: { ...ownership, firstSavedAt: '2026-01-01T00:00:00Z', lastSavedAt: '2026-01-02T00:00:00Z' } });
    const stamped = JSON.parse(stampProjectContent(original, { now: new Date('2026-11-12T16:40:31Z'), version: '1.5.0' }));
    assert.equal(stamped.ownership.owner, 'Acme Thermal Ltd');
    assert.equal(stamped.ownership.firstSavedAt, '2026-01-01T00:00:00Z');
    assert.equal(stamped.ownership.lastSavedAt, '2026-11-12T16:40:31Z');
    assert.equal(stamped.ownership.savedWith, '1.5.0');
    assert.deepEqual(stamped.nodes, [{ id: 1 }]);
    assert.deepEqual(stamped.addonData, { a: 1 });
});

test('the command line\'s save gives a project with no block its first save time, and leaves other content alone', () => {
    const stamped = JSON.parse(stampProjectContent(JSON.stringify({ format: 'konjugate', version: 1, nodes: [], edges: [] }), { now: new Date('2026-11-12T16:40:31Z') }));
    assert.deepEqual(stamped.ownership, { firstSavedAt: '2026-11-12T16:40:31Z', lastSavedAt: '2026-11-12T16:40:31Z' });
    assert.equal(stampProjectContent('not json'), 'not json');
    assert.equal(stampProjectContent('{"format":"other"}'), '{"format":"other"}');
});

test('the assistant\'s description of a model never includes the ownership block', () => {
    const summary = JSON.stringify(summarizeDocumentForAssistant(document(true)));
    assert.doesNotMatch(summary, /Acme|models@acme|MIT/);
});
